// Texto de una clave en un idioma, con el respaldo en español y luego la clave. {nombre} se reemplaza con vars.
export function translate(language, key, vars) {
  const text = translations[language]?.[key] ?? translations.es[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) => (vars[name] !== undefined ? String(vars[name]) : match));
}
